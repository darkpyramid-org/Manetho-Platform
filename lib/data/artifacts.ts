export function findArtifact(
  slugOrId: string,
): Artifact | undefined {
  return artifacts.find(
    (a) => a.slug === slugOrId || a.id === slugOrId,
  );
}

export function artifactsByMuseum(museumId: string): Artifact[] {
  return artifacts.filter((a) => a.museumId === museumId);
}

export function featuredArtifacts(): Artifact[] {
  return artifacts.filter((a) => a.featured);
}
