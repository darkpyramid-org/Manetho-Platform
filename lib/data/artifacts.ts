/**
 * Seed artifacts (spec §62).
 *
 * Metadata reflects well-documented public records for
 * real objects. This is development/demo data — always
 * verify against institutional records before production
 * use. Demo data is labelled as such throughout the UI.
 */

function artifact(partial: Omit<Artifact, "images" | "status" | "metadata" | "relatedArtifactIds" | "featured"> & {
  featured?: boolean;
  inscription?: Artifact["inscription"];
  model3D?: string;
  related?: string[];
}): Artifact {
  const { featured, inscription, model3D, related, ...rest } = partial;
  return {
    ...rest,
    images: [
      artifactImage(rest.slug, rest.name),
      artifactImage(`${rest.slug}-detail`, rest.name, "nile"),
    ],
    status: "PUBLISHED",
    metadata: {
      provenance: "Demo dataset — verify against institutional records",
    },
    relatedArtifactIds: related ?? [],
    featured: featured ?? false,
    inscription,
    model3D,
  };
}

